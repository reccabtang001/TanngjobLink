-- TangjobLink secure member access setup for Supabase
-- Run this entire file in Supabase Dashboard > SQL Editor for a NEW, separate TangjobLink project.
-- Do not use the RT Smart Learning project's database unless you intentionally want to combine them.

create table if not exists public.member_profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  email text,
  full_name text,
  username text,
  id_number text,
  amount_entered integer,
  phone text,
  selected_group text not null default 'Beginner Group' check (selected_group in ('Beginner Group','Intermediate Group','Advanced Group','Professional Group','Elite Group')),
  membership_status text not null default 'pending' check (membership_status in ('pending','active','rejected','removed')),
  payment_reference text,
  created_at timestamptz not null default now()
);

create unique index if not exists member_profiles_username_unique on public.member_profiles (lower(username)) where username is not null;

create table if not exists public.member_resources (
  id bigint generated by default as identity primary key,
  category text not null default 'US applications',
  title text not null,
  summary text not null,
  required_documents text not null default '',
  tools text not null default '',
  links jsonb not null default '[]'::jsonb,
  sort_order integer not null default 100
);

create table if not exists public.member_roles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  role text not null check (role in ('admin','member')) default 'member',
  created_at timestamptz not null default now()
);

create table if not exists public.group_meetings (
  id bigint generated by default as identity primary key,
  title text not null,
  group_name text not null check (group_name in ('All groups','Beginner Group','Intermediate Group','Advanced Group','Professional Group','Elite Group')),
  starts_at timestamptz not null,
  meeting_url text,
  notes text,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.group_messages (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  author_name text not null default 'Member',
  group_name text not null default 'Beginner Group' check (group_name in ('Beginner Group','Intermediate Group','Advanced Group','Professional Group','Elite Group')),
  message text not null check (char_length(message) between 1 and 1500),
  created_at timestamptz not null default now()
);

alter table public.member_profiles enable row level security;
create unique index if not exists member_resources_title_unique on public.member_resources (title);

alter table public.member_resources enable row level security;
alter table public.member_roles enable row level security;
alter table public.group_meetings enable row level security;
alter table public.group_messages enable row level security;

-- Only a signed-in user may read their own profile.
drop policy if exists "Users can read their own member profile" on public.member_profiles;
create policy "Users can read their own member profile" on public.member_profiles
  for select to authenticated using (auth.uid() = user_id);

drop policy if exists "Users can update their own safe profile fields" on public.member_profiles;
create policy "Users can update their own safe profile fields" on public.member_profiles
  for update to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);

-- Prevent clients from changing membership_status or email directly. Only the named columns below are client-updatable.
revoke all on public.member_profiles from anon, authenticated;
grant select on public.member_profiles to authenticated;
grant update (full_name, phone, payment_reference) on public.member_profiles to authenticated;

-- A member can select/change their group only while the membership is pending.
create or replace function public.member_choose_group(target_group text)
returns void language plpgsql security definer set search_path = public
as $$
begin
  if auth.uid() is null then raise exception 'Sign in first'; end if;
  if target_group not in ('Beginner Group','Intermediate Group','Advanced Group','Professional Group','Elite Group') then raise exception 'Invalid group'; end if;
  update public.member_profiles set selected_group = target_group
    where user_id = auth.uid() and membership_status = 'pending';
  if not found then raise exception 'Only pending members can change their selected group'; end if;
end;
$$;
revoke all on function public.member_choose_group(text) from public;
grant execute on function public.member_choose_group(text) to authenticated;

create or replace function public.is_active_tangjoblink_member()
returns boolean language sql stable security definer set search_path = public
as $$
  select exists (
    select 1 from public.member_profiles p
    where p.user_id = auth.uid() and p.membership_status = 'active'
  );
$$;
revoke all on function public.is_active_tangjoblink_member() from public;
grant execute on function public.is_active_tangjoblink_member() to authenticated;

drop policy if exists "Only active members can read lessons" on public.member_resources;
create policy "Only active members can read lessons" on public.member_resources
  for select to authenticated using (public.is_active_tangjoblink_member());
revoke all on public.member_resources from anon, authenticated;
grant select on public.member_resources to authenticated;

-- Automatically create a pending membership profile after account registration.
create or replace function public.handle_new_tangjoblink_user()
returns trigger language plpgsql security definer set search_path = public
as $$
begin
  insert into public.member_profiles (user_id, email, full_name, username, id_number, amount_entered, phone, selected_group, membership_status)
  values (new.id, new.email, new.raw_user_meta_data->>'full_name', new.raw_user_meta_data->>'username', new.raw_user_meta_data->>'id_number', nullif(new.raw_user_meta_data->>'amount_entered','')::integer, new.raw_user_meta_data->>'phone', coalesce(new.raw_user_meta_data->>'selected_group','Beginner Group'), 'pending')
  on conflict (user_id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_tangjoblink_auth_user_created on auth.users;
create trigger on_tangjoblink_auth_user_created
after insert on auth.users for each row execute procedure public.handle_new_tangjoblink_user();

-- Admin roles are assigned manually by the site owner in SQL Editor. Browser users cannot assign themselves admin.
create or replace function public.is_tangjoblink_admin()
returns boolean language sql stable security definer set search_path = public
as $$
  select exists (select 1 from public.member_roles r where r.user_id = auth.uid() and r.role = 'admin');
$$;
revoke all on function public.is_tangjoblink_admin() from public;
grant execute on function public.is_tangjoblink_admin() to authenticated;

drop policy if exists "Admins can read all member profiles" on public.member_profiles;
create policy "Admins can read all member profiles" on public.member_profiles
  for select to authenticated using (public.is_tangjoblink_admin());
drop policy if exists "Admins can update membership status" on public.member_profiles;
create policy "Admins can update membership status" on public.member_profiles
  for update to authenticated using (public.is_tangjoblink_admin()) with check (public.is_tangjoblink_admin());
-- Do NOT grant clients direct updates to membership_status; that would let a member activate themselves.
revoke update (membership_status) on public.member_profiles from authenticated;
create or replace function public.admin_set_member_status(target_user uuid, new_status text)
returns void language plpgsql security definer set search_path = public
as $$
begin
  if not public.is_tangjoblink_admin() then
    raise exception 'Administrator access required';
  end if;
  if new_status not in ('pending','active','rejected','removed') then
    raise exception 'Invalid membership status';
  end if;
  update public.member_profiles set membership_status = new_status where user_id = target_user;
  if not found then raise exception 'Member not found'; end if;
end;
$$;
revoke all on function public.admin_set_member_status(uuid, text) from public;
grant execute on function public.admin_set_member_status(uuid, text) to authenticated;

create policy "Users can read own role" on public.member_roles
  for select to authenticated using (auth.uid() = user_id or public.is_tangjoblink_admin());
revoke all on public.member_roles from anon, authenticated;
grant select on public.member_roles to authenticated;

create policy "Members can read their group meetings" on public.group_meetings
  for select to authenticated using (public.is_tangjoblink_admin() or (public.is_active_tangjoblink_member() and (group_name = 'All groups' or group_name = (select p.selected_group from public.member_profiles p where p.user_id = auth.uid()))));
create policy "Admins can create meetings" on public.group_meetings
  for insert to authenticated with check (public.is_tangjoblink_admin() and created_by = auth.uid());
create policy "Admins can update meetings" on public.group_meetings
  for update to authenticated using (public.is_tangjoblink_admin()) with check (public.is_tangjoblink_admin());
create policy "Admins can delete meetings" on public.group_meetings
  for delete to authenticated using (public.is_tangjoblink_admin());
revoke all on public.group_meetings from anon, authenticated;
grant select, insert, update, delete on public.group_meetings to authenticated;
grant usage, select on sequence public.group_meetings_id_seq to authenticated;

create policy "Members can read their group messages" on public.group_messages
  for select to authenticated using (public.is_active_tangjoblink_member() and (group_name = (select p.selected_group from public.member_profiles p where p.user_id = auth.uid()) or public.is_tangjoblink_admin()));
create policy "Members can post to their own group" on public.group_messages
  for insert to authenticated with check (public.is_active_tangjoblink_member() and user_id = auth.uid() and group_name = (select p.selected_group from public.member_profiles p where p.user_id = auth.uid()));
create policy "Admins can delete group messages" on public.group_messages
  for delete to authenticated using (public.is_tangjoblink_admin());
revoke all on public.group_messages from anon, authenticated;
grant select, insert, delete on public.group_messages to authenticated;
grant usage, select on sequence public.group_messages_id_seq to authenticated;

